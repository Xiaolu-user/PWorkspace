const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { randomUUID } = require('node:crypto')
const root = resolve(__dirname, '..'), output = join(root, 'test-results/home'), data = join(root, '.cache', `home-${randomUUID()}`)
mkdirSync(output, { recursive: true }); mkdirSync(data, { recursive: true })
const env = { ...process.env, WORKBENCH_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL
let app, page; const errors = [], checks = []
async function api(group, method, ...args) { const r = await page.evaluate(async ({ group, method, args }) => window.workbench[group][method](...args), { group, method, args }); assert.equal(r.ok, true, JSON.stringify(r)); return r.data }
async function launch() { app = await electron.launch({ executablePath: require('electron'), args: [root], cwd: root, env }); page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message)); await page.waitForFunction(() => document.querySelector('.page-footer')?.textContent.includes('v0.1.0')); }
async function stop() { if (app) { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); app = null } }
async function main() {
  await launch()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1600, 960))
  assert.equal(await page.locator('.error-banner').count(), 0)
  await page.screenshot({ path: join(output, 'empty.png') })
  await page.getByRole('button', { name: '添加今日待办' }).click()
  await page.getByPlaceholder('接下来，想完成什么？').fill('完成高数课后练习')
  await page.getByRole('dialog').getByRole('button', { name: '添加任务', exact: true }).click()
  await page.getByRole('checkbox', { name: '完成任务：完成高数课后练习' }).check()
  assert.equal((await api('tasks', 'list'))[0].status, 'done'); checks.push('首页新增默认今天及勾选完成')
  await page.getByRole('textbox', { name: '灵感内容' }).fill('一个中文灵感\n第二行想法')
  await page.getByRole('link', { name: '我的待办', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  assert.equal(await page.getByRole('textbox', { name: '灵感内容' }).inputValue(), '一个中文灵感\n第二行想法')
  await page.getByRole('textbox', { name: '灵感内容' }).press('Control+Enter')
  await page.waitForFunction(() => document.querySelector('.idea-input textarea').value === '')
  assert.equal((await api('notes', 'list'))[0].body, '一个中文灵感\n第二行想法'); checks.push('灵感未保存导航拦截及快捷键保存')
  await page.getByRole('button', { name: '学期课程', exact: false }).first().click()
  await page.getByPlaceholder('例如：2026 秋季学期').fill('测试学期')
  await page.getByPlaceholder('选择开学日期').fill('2026-09-01'); await page.getByPlaceholder('选择开学日期').press('Enter')
  await page.getByRole('button', { name: '添加课程', exact: false }).click()
  await page.getByRole('textbox', { name: '课程名称', exact: true }).fill('高等数学')
  await page.getByRole('button', { name: '保存计划' }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal((await api('planner', 'get')).semester.courses[0].title, '高等数学'); checks.push('学期课程表单保存')
  for (let i = 0; i < 2; i++) {
    await page.getByRole('link', { name: '课程表', exact: true }).click()
    await page.getByRole('dialog', { name: '学期课程', exact: true }).waitFor()
    await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
    await page.waitForFunction(() => !location.hash.includes('panel='))
  }
  checks.push('导航课程入口关闭后可再次打开')
  await page.getByRole('button', { name: '制定计划', exact: false }).click()
  await page.getByPlaceholder('训练名称（留空为休息日）').first().fill('上肢力量')
  await page.getByRole('button', { name: '保存计划' }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal((await api('planner', 'get')).workouts[0].title, '上肢力量'); checks.push('七天健身计划保存')
  const file = join(data, '中文资料.txt'); writeFileSync(file, '本地文件')
  await app.evaluate(({ dialog, shell }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); global.__opened = []; shell.openPath = async path => { global.__opened.push(path); return '' } }, file)
  await page.getByRole('button', { name: '点击添加文件入口' }).click()
  await page.getByRole('button', { name: '中文资料.txt', exact: false }).first().click()
  assert.deepEqual(await app.evaluate(() => global.__opened), [file]); checks.push('资料选择入库及打开调度（原生对话框和外部程序已替身）')
  const localToday = await page.evaluate(() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}` })
  const day = new Date(`${localToday}T12:00:00`).getDay() || 7
  await api('planner','semester',{ title:'2026 秋季学期',startDate:localToday,weeks:18,courses:[{ id:'',title:'高等数学',room:'教学楼 A302',day,start:'08:00',end:'09:40',firstWeek:1,lastWeek:18,parity:'all'},{ id:'',title:'大学英语',room:'教学楼 B205',day,start:'15:00',end:'16:40',firstWeek:1,lastWeek:18,parity:'all'}] })
  await api('planner','workouts',[{ day,title:'上肢力量',minutes:45,exercises:'热身拉伸　5分钟\n俯卧撑　3组 × 12次\n哑铃划船　3组 × 12次\n平板支撑　3组 × 45秒' }])
  for (const title of ['整理课程笔记','提交小组作业','阅读20分钟']) await api('tasks','create',{ title,description:'把眼前的一件事认真做好',dueDate:localToday,status:'todo',priority:'normal' })
  for (const title of ['GitHub','哔哩哔哩','校园门户','邮箱','飞书','腾讯会议','学习资料','设计参考','音乐','技术文档','阅读清单','项目笔记','课程平台','图书馆','日历','相册','网盘','个人主页']) await api('bookmarks','create',{ title,url:'https://example.com',group:'测试快捷方式' })
  await page.reload(); await page.waitForFunction(() => document.querySelectorAll('.shortcut-tile').length === 18)
  await page.screenshot({ path: join(output,'home-1600.png') })
  for (const size of [[1320,860],[960,640]]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setContentSize(...size), size)
    await page.waitForTimeout(300)
    assert.equal(await page.evaluate(() => document.querySelector('.page-scroll').scrollWidth > document.querySelector('.page-scroll').clientWidth), false)
    await page.screenshot({ path: join(output,`home-${size[0]}.png`) })
  }
  checks.push('1600 / 1320 / 960 窗口布局无横向溢出')
  await stop(); await launch()
  const restored = await api('planner','get'); assert.equal(restored.semester.title,'2026 秋季学期'); assert.equal(restored.entries.length,1); assert.equal(restored.workouts[0].title,'上肢力量'); checks.push('退出重开保留课程、健身与资料')
  assert.deepEqual(errors,[])
  writeFileSync(join(output,'report.json'),JSON.stringify({ checks,errors,data },null,2)); console.log(checks.join('\n'))
}
main().catch(async e => { console.error(e); if(page) await page.screenshot({path:join(output,'failure.png')}).catch(()=>{}); process.exitCode=1 }).finally(stop)
