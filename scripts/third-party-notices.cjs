// Collect license texts for the desktop runtime and bundled UI dependency trees.
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const pkg = require('../package.json')
const roots = [...Object.keys(pkg.dependencies), 'vue', 'vue-router', 'pinia', 'element-plus', '@element-plus/icons-vue', 'lunar-typescript']
const visited = new Set(), entries = []
function locate(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name)
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate
    if (path.dirname(dir) === dir) throw new Error(`Missing installed dependency: ${name}`)
  }
}
function collect(name, from) {
  const dir = locate(name, from)
  if (visited.has(dir)) return
  visited.add(dir)
  const info = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const files = fs.readdirSync(dir).filter(file => /^(?:licen[cs]e|copying|notice)(?:[.-]|$)/i.test(file) && fs.statSync(path.join(dir, file)).isFile()).sort()
  const supplemental = { '@vue/devtools-api@6.6.4': 'vue-devtools-api-6.6.4.txt', 'lodash-unified@1.0.3': 'lodash-unified-1.0.3.txt' }[`${info.name}@${info.version}`]
  if (!files.length && !supplemental) throw new Error(`License text not found: ${info.name}@${info.version}`)
  const text = files.length ? files.map(file => `${file}\n${fs.readFileSync(path.join(dir, file), 'utf8').trim()}`).join('\n\n') : fs.readFileSync(path.join(root, 'resources/licenses', supplemental), 'utf8').trim()
  entries.push({ name: info.name, version: info.version, license: info.license, text })
  for (const dependency of Object.keys(info.dependencies || {})) collect(dependency, dir)
}
for (const name of roots) collect(name, root)
entries.sort((a, b) => a.name.localeCompare(b.name, 'en') || a.version.localeCompare(b.version, 'en'))
const introduction = `Third-party notices for 大内总管

Generated by node scripts/third-party-notices.cjs from installed dependencies.
This list includes the declared dependency trees of the runtime and bundled UI;
some listed packages are used only during compilation or in development branches.
Each component remains subject to its own license below.

Electron and Chromium notices are shipped beside the executable in LICENSE.electron.txt
and LICENSES.chromium.html. SQLite and other native component notices remain in
their respective package licenses. Exercise metadata uses the Unlicense; see
out/renderer/fitness/EXERCISE-LICENSE.txt and SOURCES.md in the application archive.
Project artwork provenance is documented in resources/icon-prompt.md and
resources/fitness/ARTWORK.md in the source repository.
`
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.txt'), introduction + entries.map(entry => `\n${'='.repeat(72)}\n${entry.name}@${entry.version} (${entry.license})\n${'='.repeat(72)}\n${entry.text}\n`).join(''))
console.log(`Collected license texts for ${entries.length} dependencies.`)
