const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { randomUUID } = require('node:crypto')
const root = resolve(__dirname, '..'), output = join(root, 'test-results/display'), data = join(root, '.cache', `display-${randomUUID()}`)
mkdirSync(output, { recursive: true }); mkdirSync(data, { recursive: true })
const env = { ...process.env, WORKBENCH_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL
let app, page; const errors = [], checks = []
async function api(group, method, ...args) { const result = await page.evaluate(async ({ group, method, args }) => window.workbench[group][method](...args), { group, method, args }); assert.equal(result.ok, true, JSON.stringify(result)); return result.data }
async function launch() { app = await electron.launch({ executablePath: require('electron'), args: [root], cwd: root, env }); page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message)); await page.waitForFunction(version => document.querySelector('.page-footer')?.textContent.includes('v' + version), require('../package.json').version); await app.evaluate(({ Notification }) => { Notification.isSupported = () => true; Notification.prototype.show = function () { this.emit('show') } }) }
async function stop() { if (app) { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); app = null } }
async function selectOption(form, name, option) { await form.getByRole('combobox', { name, exact: true }).press('Enter'); await page.getByRole('option', { name: option, exact: true }).click() }
async function main() {
  await launch(); await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1600, 1000))
  const dates = await page.evaluate(() => { const format = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`; const date = new Date(); const today = format(date); date.setDate(date.getDate() + 1); return { today, tomorrow: format(date) } })
  await api('tasks','create',{ title:'普通事项',description:'今天的普通待办',status:'todo',priority:'high',dueDate:dates.today })
  const reminder = await api('tasks','create',{ title:'准备明日读书分享',description:'提醒已触发，完成前保持置顶',status:'todo',priority:'low',dueDate:dates.tomorrow,dueTime:'09:00',remindBefore:43200 })
  await page.reload(); await page.getByRole('button', {name:'我已知晓',exact:true}).waitFor()
  assert.match(await page.locator('.home-task').first().textContent(), /准备明日读书分享/)
  assert.equal(await page.locator('.home-task').first().evaluate(el => getComputedStyle(el).animationName), 'reminder-pulse')
  await page.screenshot({ animations: "disabled", path:join(output,'reminder-flashing.png')})
  await page.getByRole('button',{name:'我已知晓',exact:true}).click()
  await page.waitForFunction(() => !document.querySelector('.home-task')?.classList.contains('reminder-flashing'))
  assert.ok(await page.locator('.home-task').first().evaluate(el => el.classList.contains('reminder-active')))
  assert.ok((await api('tasks','get',reminder.id)).reminderAcknowledgedAt)
  await page.reload(); await page.locator('.home-task.reminder-active').waitFor()
  assert.equal(await page.locator('.home-task.reminder-flashing').count(),0)
  checks.push('跨日期提醒置顶闪烁、确认后停止闪烁且保留高亮、刷新保留确认')
  const titleSize = await page.locator('.home-task strong').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize))
  assert.ok(titleSize >= 18, `今日待办字号 ${titleSize}`)
  await page.getByRole('button',{name:'打开日历',exact:true}).click()
  const calendar = page.getByRole('dialog',{name:'日历与待办',exact:true}); await calendar.waitFor()
  await calendar.locator('[data-date="2026-10-20"]').click()
  await calendar.getByRole('spinbutton',{name:'跳转数量',exact:true}).fill('10')
  await calendar.getByRole('button',{name:'跳转',exact:true}).click()
  assert.equal(await calendar.locator('[data-date="2026-10-30"]').getAttribute('aria-pressed'),'true')
  assert.ok(await calendar.locator('[data-date="2026-10-01"] .calendar-event-dot').count() > 1)
  assert.match(await calendar.locator('[data-date="2026-10-10"] .calendar-holiday-tag').textContent(), /班/)
  await page.screenshot({ animations: "disabled", path:join(output,'calendar-holidays.png')})
  await selectOption(calendar,'跳转单位','月')
  await calendar.getByRole('spinbutton',{name:'跳转数量',exact:true}).fill('1')
  await calendar.getByRole('button',{name:'跳转',exact:true}).click()
  assert.equal(await calendar.locator('[data-date="2026-11-30"]').getAttribute('aria-pressed'),'true')
  await selectOption(calendar,'跳转单位','年')
  await calendar.getByRole('button',{name:'跳转',exact:true}).click()
  assert.equal(await calendar.locator('[data-date="2027-11-30"]').getAttribute('aria-pressed'),'true')
  await page.keyboard.press('Escape'); await calendar.waitFor({state:'hidden'})
  checks.push('10 日后、1 月后和1 年后以选中日累计跳转，节日置于数字上方并显示补班')
  await page.getByRole('button',{name:'添加今日待办',exact:false}).click()
  let form = page.getByRole('dialog',{name:'添加一件要做的事',exact:true}); await form.waitFor()
  const width = (await form.boundingBox()).width; assert.ok(width >= 790, `弹窗宽度 ${width}`)
  assert.ok(await form.locator('.el-form-item__label').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 16))
  await page.screenshot({ animations: "disabled", path:join(output,'larger-task-dialog.png')})
  await form.getByRole('button',{name:'取消',exact:true}).click(); await form.waitFor({state:'hidden'})
  await page.getByRole('link',{name:'设置与备份',exact:true}).click()
  await page.getByRole('spinbutton',{name:'全局文字大小',exact:true}).fill('120')
  await page.getByRole('spinbutton',{name:'弹窗大小',exact:true}).fill('135')
  await page.getByRole('spinbutton',{name:'弹窗文字大小',exact:true}).fill('130')
  await page.getByRole('spinbutton',{name:'今日待办模块大小',exact:true}).fill('120')
  await page.getByRole('spinbutton',{name:'今日待办文字大小',exact:true}).fill('125')
  await page.getByRole('button',{name:'保存显示设置',exact:true}).click()
  await page.getByText('显示设置已保存并生效',{exact:true}).waitFor()
  let preferences = await api('app','preferences'); assert.equal(preferences.appearance.modules.todos.scale,120); assert.equal(preferences.appearance.fontScale,120)
  await page.screenshot({ animations: "disabled", path:join(output,'display-settings.png')})
  await page.getByRole('link',{name:'今日概览',exact:true}).click()
  assert.equal(await page.locator('.home-tasks').evaluate(el => Number(getComputedStyle(el).zoom)),1.2)
  assert.ok(await page.locator('.home-task strong').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize) > 24))
  for (const size of [[1600,1000],[1320,860],[960,640]]) {
    await app.evaluate(({BrowserWindow}, size) => BrowserWindow.getAllWindows()[0].setContentSize(...size),size)
    await page.waitForTimeout(250)
    assert.equal(await page.locator('.page-scroll').evaluate(el => el.scrollWidth > el.clientWidth),false, `模块缩放后 ${size[0]} 宽窗口无横向溢出`)
    await page.getByRole('button',{name:'打开日历',exact:true}).click(); await calendar.waitFor()
    const bounds = await calendar.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x+bounds.width <= size[0]); assert.ok(bounds.y+bounds.height <= size[1])
    await page.screenshot({ animations: "disabled", path:join(output,`calendar-${size[0]}.png`)})
    await page.keyboard.press('Escape'); await calendar.waitFor({state:'hidden'})
  }
  checks.push('弹窗框体、字号和控件放大；逐模块缩放和文字配置生效；三种窗口尺寸无横向溢出')
  await stop(); await launch()
  preferences = await api('app','preferences'); assert.equal(preferences.appearance.modules.todos.fontScale,125); assert.equal(preferences.appearance.dialogScale,135)
  assert.ok((await api('tasks','get',reminder.id)).reminderAcknowledgedAt)
  await page.getByRole('checkbox',{name:'完成任务：准备明日读书分享',exact:true}).click()
  await page.waitForFunction(() => !document.querySelector('.home-task.reminder-active'))
  assert.equal((await api('tasks','get',reminder.id)).status,'done')
  checks.push('显示配置与确认状态重启后保留，勾选完成后解除置顶高亮')
  assert.deepEqual(errors,[])
  writeFileSync(join(output,'report.json'),JSON.stringify({checks,errors,data},null,2)); console.log(checks.join('\n'))
}
main().catch(async error => { console.error(error); if(page) await page.screenshot({ animations: "disabled", path:join(output,'failure.png')}).catch(()=>{}); process.exitCode=1 }).finally(stop)
